"""
Comprehensive Athlete Report Generation Service.
Generates structured summaries in JSON, CSV, and HTML/PDF formats.
Includes clear medical disclaimers and model version transparency.
"""
import io
import csv
import time
import json
from typing import Dict, Any, Optional

def generate_athlete_report(athlete: dict, session: Optional[dict], measurements: list, alerts: list, risk_eval: dict) -> Dict[str, Any]:
    generated_at = time.time()
    
    # Summary calculations
    risks = [m.get("overall_risk", 0.0) for m in measurements if "overall_risk" in m]
    avg_risk = round(sum(risks) / len(risks), 4) if risks else athlete.get("current_risk", 0.0)
    peak_risk = round(max(risks), 4) if risks else athlete.get("current_risk", 0.0)
    
    report_dict = {
        "report_id": f"REP-{athlete.get('id', '00')}-{int(generated_at)}",
        "generated_at": generated_at,
        "generated_date_str": time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(generated_at)),
        "athlete_info": {
            "id": athlete.get("id"),
            "name": athlete.get("name"),
            "position": athlete.get("position"),
            "sport": athlete.get("sport", "Football"),
            "status": athlete.get("status")
        },
        "session_summary": {
            "session_id": session.get("id") if session else "N/A",
            "type": session.get("type", "Training") if session else "General Monitoring",
            "duration_min": session.get("duration_min", 0) if session else 0,
            "average_risk_score": avg_risk,
            "peak_risk_score": peak_risk,
            "alerts_count": len(alerts)
        },
        "recent_alerts": alerts[:10],
        "model_evaluation_metrics": risk_eval,
        "disclaimer": (
            "This report is generated by the AI-Based Real-Time Sports Injury Monitoring System. "
            "All indices, risk scores, and recommendations represent statistical decision-support "
            "indicators and do not constitute a medical diagnosis or treatment plan."
        )
    }
    return report_dict

def export_report_csv(report: dict) -> str:
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["REPORT SUMMARY", report.get("report_id")])
    writer.writerow(["Date", report.get("generated_date_str")])
    writer.writerow(["Athlete ID", report["athlete_info"]["id"]])
    writer.writerow(["Athlete Name", report["athlete_info"]["name"]])
    writer.writerow(["Sport", report["athlete_info"]["sport"]])
    writer.writerow([])
    writer.writerow(["SESSION SUMMARY"])
    for k, v in report["session_summary"].items():
        writer.writerow([k, v])
    writer.writerow([])
    writer.writerow(["ALERTS"])
    writer.writerow(["Timestamp", "Severity", "Reason", "Acknowledged"])
    for a in report.get("recent_alerts", []):
        writer.writerow([a.get("timestamp"), a.get("level") or a.get("severity"), a.get("reason"), a.get("acknowledged")])
    writer.writerow([])
    writer.writerow(["DISCLAIMER", report.get("disclaimer")])
    return output.getvalue()
